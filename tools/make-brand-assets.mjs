// Builds every logo asset from the traced signature (tools/assets/signature-path.json, made by trace-signature.py):
//   components/icons/Logo.tsx                          the React component (colour from `currentColor`)
//   public/assets/brand/logo-stamp-{light,dark}.png    the signature painted on the home page's 3D orb
//   public/signature-apple-icon.png                    home-screen icon (180x180)
//   public/signature-favicon.png                       browser tab icon
//   public/assets/brand/social-card.png                1200x630 share image
// The signature is hairline-thin, so wherever it is small it gets a stroke (the `weight`) that thickens it a little.
// Colours are the site's own: brand blue for light mode, white for dark mode, paper behind.
//
//   python3 tools/trace-signature.py && node tools/make-brand-assets.mjs
import fs from 'node:fs';
import { chromium } from 'playwright';

const { d, width: W, height: H } = JSON.parse(fs.readFileSync('tools/assets/signature-path.json', 'utf8'));
const BLUE = '#9a0002'; // --hermes-color-blue (Cherry Cola)
const WHITE = '#efe6de'; // Cream Vanilla
const PAD = 12; // room around the drawing so the stroke is not clipped
const VB = `${-PAD} ${-PAD} ${W + 2 * PAD} ${(H + 2 * PAD).toFixed(2)}`;
const ASPECT = (W + 2 * PAD) / (H + 2 * PAD);

fs.mkdirSync('public/assets/brand', { recursive: true });

// 1. the component: an <svg> that <use>s the shared path, so the 60 KB outline is cached once instead of inlined
fs.writeFileSync(
  'components/icons/Logo.tsx',
  `import type { SVGProps } from 'react';

/**
 * The site's logo: Animesh's signature. It is one shape drawn in \`currentColor\` (blue in light mode, white in
 * dark mode) from public/assets/brand/signature-sprite.svg. \`weight\` is a stroke in drawing units (the drawing is
 * ${W} wide) that thickens the hairlines; use a bigger one when the logo is small.
 * Generated by tools/make-brand-assets.mjs; do not edit by hand.
 */
export function Logo({ weight = 7, ...props }: SVGProps<SVGSVGElement> & { weight?: number }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="${VB}"
      fill="currentColor"
      stroke="currentColor"
      strokeWidth={weight}
      strokeLinejoin="round"
      strokeLinecap="round"
      {...props}
    >
      <use href="/assets/brand/signature-sprite.svg#signature" />
    </svg>
  );
}

/** Width divided by height of the logo, for sizing it. */
export const LOGO_ASPECT = ${ASPECT.toFixed(4)};
`,
);

// 2. the orb stamps (PNG, drawn in Chromium below): the signature centred on a transparent square canvas.
//    They are rasters rather than SVG so every browser maps exactly the same pixels onto the 3D medal.
const side = 983;
const stampW = 700;
const k = stampW / W;
const tx = (side - stampW) / 2;
const ty = (side - H * k) / 2;
const stampSvg = (fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${side}" height="${side}" viewBox="0 0 ${side} ${side}"><g transform="translate(${tx} ${ty.toFixed(2)}) scale(${k})"><path fill="${fill}" stroke="${fill}" stroke-width="9" stroke-linejoin="round" d="${d}"/></g></svg>`;

// 3 + 4. raster images, drawn in Chromium
const mark = (color, width, weight) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VB}" width="${width}" fill="${color}" stroke="${color}" stroke-width="${weight}" stroke-linejoin="round" stroke-linecap="round"><path d="${d}"/></svg>`;
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH ?? ['/opt/pw-browsers/chromium-1194/chrome-linux/chrome', '/opt/pw-browsers/chromium'].find((p) => fs.existsSync(p)),
});
const stampPage = await browser.newPage({ viewport: { width: side, height: side }, deviceScaleFactor: 2 });
for (const [theme, fill] of [['light', BLUE], ['dark', '#efe6de']]) {
  await stampPage.setContent(`<body style="margin:0;background:transparent">${stampSvg(fill)}</body>`);
  await stampPage.screenshot({ path: `public/assets/brand/logo-stamp-${theme}.png`, omitBackground: true });
}
const page = await browser.newPage();

await page.setViewportSize({ width: 96, height: 96 });
await page.setContent(`<body style="margin:0;background:${BLUE};display:grid;place-items:center;width:96px;height:96px">${mark(WHITE, 88, 34)}</body>`);
await page.screenshot({ path: 'public/signature-favicon.png' });

await page.setViewportSize({ width: 180, height: 180 });
await page.setContent(`<body style="margin:0;background:${BLUE};display:grid;place-items:center;width:180px;height:180px">${mark(WHITE, 160, 22)}</body>`);
await page.screenshot({ path: 'public/signature-apple-icon.png' });

await page.setViewportSize({ width: 1200, height: 630 });
await page.setContent(`<body style="margin:0;background:${BLUE};display:grid;place-items:center;width:1200px;height:630px">${mark(WHITE, 860, 6)}</body>`);
await page.screenshot({ path: 'public/assets/brand/social-card.png' });
await browser.close();
const { execFileSync } = await import('node:child_process');
execFileSync('python3', ['-c', "from PIL import Image; Image.open('public/signature-favicon.png').save('public/favicon.ico', sizes=[(16,16),(32,32),(48,48),(64,64)])"]);
console.log('wrote Logo.tsx, orb stamps, favicon (.ico and .png), apple icon and social card');
